export function translateLegacyText(locale, source) {
  if (!source || locale === 'vi') return source;
  const exact = catalogs[locale]?.get(source);
  if (exact) return exact;
  for (const [pattern, formatter] of templates) {
    const match = source.match(pattern);
    if (match) return formatter(locale, ...match.slice(1));
  }
  return source;
}
