export function normalizeLocale(locale) {
  if (locale === 'zh') return 'zh-CN';
  return SUPPORTED_LOCALES.includes(locale) ? locale : DEFAULT_LOCALE;
}

export function getIntlLocale(locale) {
  return LOCALE_META[normalizeLocale(locale)].intlLocale;
}

export function interpolate(message, values = {}) {
  return String(message).replace(/\{(\w+)\}/g, (match, name) => (
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match
  ));
}

export function translate(locale, key, values) {
  const normalized = normalizeLocale(locale);
  const message = translations[normalized]?.[key]
    ?? translations[DEFAULT_LOCALE]?.[key]
    ?? translations.en?.[key]
    ?? key;
  return interpolate(message, values);
}

export function translateDataLabel(locale, value) {
  if (!value) return value;
  const normalized = normalizeLocale(locale);
  for (const key of [`category.${value}`, `type.${value}`]) {
    if (translations[normalized]?.[key] || translations[DEFAULT_LOCALE]?.[key]) {
      return translate(normalized, key);
    }
  }
  return value;
}
