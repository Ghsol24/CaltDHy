export function useBudgetCopy() {
  const { t, lang } = useTranslation();
  const copy = BUDGET_COPY[normalizeLocale(lang)] || BUDGET_COPY.vi;
  return useCallback(
    (key, values) => (copy[key] !== undefined ? interpolate(copy[key], values) : t(key, values)),
    [copy, t]
  );
}
