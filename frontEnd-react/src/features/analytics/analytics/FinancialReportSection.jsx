import React from 'react';
import { NavIcon } from '../../../components/ui/NavIcons';
import { Icon } from '../../../components/ui/AppIcons';
import { BrandMark } from '../../../components/ui/BrandMark';
import { useAuthStore } from '../../../stores/useAuthStore';
import { useTranslation } from '../../../i18n/useTranslation';
import { formatDate, getLocalDateString } from '../../../utils/formatters';
import { ReportSummaryCards } from './ReportSummaryCards';
import { ReportInsightsBanner } from './ReportInsightsBanner';
import { ReportCategoryTable } from './ReportCategoryTable';

const PRINT_COPY = {
  vi: {
    subtitle: 'Báo cáo tổng hợp tài chính',
    period: 'Kỳ báo cáo:',
    compare: 'Đối chiếu kỳ liền kề:',
    exported: 'Ngày xuất:',
    preparedBy: 'Người lập:',
    footer: 'Được tạo từ CaltDHy — Quản lý tài chính cá nhân',
    confidential: 'Dữ liệu tài chính cá nhân',
  },
  en: {
    subtitle: 'Financial Summary Report',
    period: 'Reporting period:',
    compare: 'Compared with:',
    exported: 'Exported:',
    preparedBy: 'Prepared for:',
    footer: 'Generated by CaltDHy — Personal Finance',
    confidential: 'Personal financial statement',
  },
  'zh-CN': {
    subtitle: '财务综合报告',
    period: '报告周期：',
    compare: '对比上期：',
    exported: '导出日期：',
    preparedBy: '账户：',
    footer: '由 CaltDHy 个人财务管理生成',
    confidential: '个人财务数据',
  },
};

export function FinancialReportSection({ activeMonth, curQuarterMonths, handleExportCSV, handlePrint, visible, reportData, reportPeriodType, setReportPeriodType, viewCategoryHistory }) {
  const { lang } = useTranslation();
  const userName = useAuthStore((state) => state.user?.name);
  const printCopy = PRINT_COPY[lang] || (String(lang).startsWith('zh') ? PRINT_COPY['zh-CN'] : PRINT_COPY.vi);
  const printedDate = formatDate(getLocalDateString(), 'short', { locale: lang });

  return (visible && (
  <>
  <div className="analytics-section-panel analytics-report-section" id="analytics-reports">
    {/* Print-only Branded Letterhead (hidden on screen via .report-print-only) */}
    <header className="report-print-only report-print-letterhead">
      <div className="report-print-letterhead__row">
        <div className="report-print-letterhead__brand">
          <BrandMark variant="full" className="report-print-logo" />
          <div>
            <div className="report-print-brand-name">
              Calt<span className="report-print-brand-accent">D</span>Hy
            </div>
            <div className="report-print-brand-sub">{printCopy.subtitle}</div>
          </div>
        </div>
        <div className="report-print-meta">
          <div>{printCopy.period} <strong>{reportData.curLabel}</strong></div>
          <div>{printCopy.compare} <strong>{reportData.prevLabel}</strong></div>
          <div>
            {printCopy.exported} <strong>{printedDate}</strong>
            {userName ? <> · {printCopy.preparedBy} <strong>{userName}</strong></> : null}
          </div>
        </div>
      </div>
    </header>

    {/* Header & Controls */}
    <div className="panel-header">
      <div className="panel-titles">
        <h2 className="panel-main-title panel-main-title--layout">
          <NavIcon name="reports" size={18} /> Báo cáo tổng hợp tài chính
        </h2>
      </div>
  
      <div className="report-action-bar">
        {/* Period Mode Selector: Tháng | Quý */}
        <div className="analytics-segmented-switch" role="radiogroup" aria-label="Chế độ báo cáo">
          <button
            type="button"
            role="radio"
            aria-checked={reportPeriodType === 'monthly'}
            className={`analytics-segment-btn ${reportPeriodType === 'monthly' ? 'active' : ''}`}
            onClick={() => setReportPeriodType('monthly')}
          >
            Theo Tháng
          </button>
          <button
            type="button"
            role="radio"
            aria-checked={reportPeriodType === 'quarterly'}
            className={`analytics-segment-btn ${reportPeriodType === 'quarterly' ? 'active' : ''}`}
            onClick={() => setReportPeriodType('quarterly')}
          >
            Theo Quý
          </button>
        </div>
  
        {/* Print & Export Buttons */}
        <button
          type="button"
          className="btn-report-action"
          onClick={handlePrint}
          title="In hoặc Lưu thành file PDF"
        >
          <Icon name="printer" width="15" height="15" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" />
          <span>In báo cáo</span>
        </button>
  
        <button
          type="button"
          className="btn-report-action"
          onClick={handleExportCSV}
          title="Tải bảng tính sao kê chi tiết dạng CSV (tương thích Excel)"
        >
          <Icon name="download" width="15" height="15" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" />
          <span>Xuất CSV</span>
        </button>
      </div>
    </div>
  
    {/* Period info pill */}
    <div className="analytics-section-panel__div--layout">
      <span className="report-period-tag report-period-tag--layout">
        <Icon name="calendar" width="14" height="14" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" />
        <span>Kỳ báo cáo: <strong>{reportData.curLabel}</strong></span>
      </span>
      <span className="analytics-section-panel__span--text">
        (Đối chiếu với kỳ liền kề: <strong>{reportData.prevLabel}</strong>)
      </span>
    </div>
  
    {/* The four headline figures live once, at the top of the page. This copy exists
        only for the printed report (see print.css). */}
    <div className="report-print-only"><ReportSummaryCards reportData={reportData} /></div>
  
    {/* Smart Financial Insights & Advice Banner */}
    {<ReportInsightsBanner reportData={reportData} />}
  
    {/* Detailed Category Table */}
    <ReportCategoryTable activeMonth={activeMonth} curQuarterMonths={curQuarterMonths} reportData={reportData} reportPeriodType={reportPeriodType} viewCategoryHistory={viewCategoryHistory} />

    {/* Print-only Branded Footer */}
    <footer className="report-print-only report-print-footer">
      <div className="report-print-footer__row">
        <span className="report-print-footer__brand">
          <BrandMark className="report-print-footer-logo" />
          <span>{printCopy.footer}</span>
        </span>
        <span>{printCopy.confidential}</span>
      </div>
    </footer>
  </div>
  </>
  )) || null;
}
